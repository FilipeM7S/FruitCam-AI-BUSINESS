for (const [n, kind, rate] of [["4", "good", 0.1], ["5", "rotten", 0.2]]) {
  test(`${n} growth ${kind}: bars equal the known +${rate * 100}% per month, first period is n/a`, { skip }, () => {
    const s = growthSeries(F.growth.payload, kind);
    const err = Math.max(...s.count.slice(1).map((v) => Math.abs(v - rate)));
    near(err, 0, 0.003, `${kind} count growth`);
    assert.deepEqual(s.na, [0]);
    assert.deepEqual(s.sign.slice(1), Array(s.sign.length - 1).fill(1));
    assert.equal(s.last.index, s.count.length - 1);
    const range = growthRange(F.growth.payload);
    assert.equal(range.min, -range.max);
    say(`max |bar - ${rate}| = ${err.toExponential(1)}, n/a at ${JSON.stringify(s.na)}, shared range ±${range.max.toFixed(3)}`);
  });
}

test("4/5 growth with previous = 0: n/a markers exactly where growth is undefined, never zero", { skip }, () => {
  const g = growthSeries(F.growth_zero.payload, "good");
  const r = growthSeries(F.growth_zero.payload, "rotten");
  assert.deepEqual(g.na, F.growth_zero.truth.good_na);
  assert.deepEqual(r.na, F.growth_zero.truth.rotten_na);
  assert.equal(g.count[1], -1);
  assert.equal(g.sign[1], -1);
  near(r.count[3], 0.5, 1e-12, "rotten Apr");
  assert.ok([...g.na, ...r.na].every((i) => (i < g.count.length ? true : false)));
  assert.ok(g.na.every((i) => g.count[i] === null) && r.na.every((i) => r.count[i] === null));
  say(`good n/a ${JSON.stringify(g.na)}, rotten n/a ${JSON.stringify(r.na)}, good Feb ${g.count[1]}, rotten Apr ${r.count[3]}`);
});

