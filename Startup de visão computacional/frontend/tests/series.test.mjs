import assert from "node:assert/strict";
import fs from "node:fs";
import { test } from "node:test";
import { deformitySeries, forecastSeries, fruitSeries, gaussianSeries, growthRange, growthSeries, overviewSeries, recurringSeries } from "../src/series.js";

const fixturePath = process.env.FRUITCAM_FIXTURES;
const F = fixturePath ? JSON.parse(fs.readFileSync(fixturePath, "utf8")) : null;
const skip = F ? false : "set FRUITCAM_FIXTURES (generated by core.test_dashboard)";
const near = (a, b, tol, what) => assert.ok(Math.abs(a - b) <= tol, `${what}: |${a} - ${b}| > ${tol}`);
const say = (...a) => console.log("    ", ...a);

test("1 deformity: the highlighted segment is the true dominant type of every week", { skip }, () => {
  const { payload, truth } = F.deformity;
  const s = deformitySeries(payload);
  let correct = 0;
  let worst = 0;
  truth.dominant.forEach((top, w) => {
    if (top === "none") {
      assert.ok(s.types.every((t) => s.dominant[t][w] === false && s.shares[t][w] === null), `week ${w} should be empty`);
      return;
    }
    if (top === "tie") {
      assert.ok(s.types.every((t) => s.dominant[t][w]), `week ${w} tie should highlight all`);
      return;
    }
    assert.ok(s.dominant[top][w] && s.types.filter((t) => s.dominant[t][w]).length === 1, `week ${w} should highlight only ${top}`);
    correct++;
    worst = Math.max(worst, Math.abs(s.shares[top][w] - 0.6));
  });
  near(worst, 0, 0.1, "dominant share vs true 0.6");
  assert.deepEqual(s.empty, truth.empty);
  assert.equal(s.latest.type, truth.dominant[truth.dominant.length - 1]);
  const sums = payload.weeks.map((_, w) => s.types.reduce((a, t) => a + (s.shares[t][w] ?? 0), 0)).filter((v) => v > 0);
  sums.forEach((v) => near(v, 1, 1e-12, "stacked shares sum"));
  say(`highlighted = true dominant in ${correct}/${correct} weeks; max |share-0.6| = ${worst.toFixed(4)}; empty weeks ${JSON.stringify(s.empty)}; stacked sums = 1`);
});

test("2 forecast: history, fan and forecast point match the known trend", { skip }, () => {
  const { payload, truth } = F.forecast;
  const items = Object.fromEntries(payload.sectors.map((x) => [x.sector, forecastSeries(x, payload.labels, payload.target_period)]));
  const r = items.rising;
  const n = r.labels.length - 1;
  near(r.forecast[n], truth.rising_next, 0.03, "forecast point vs true next value");
  assert.ok(r.lo[n] <= truth.rising_next && truth.rising_next <= r.hi[n], "true value inside the fan at the forecast point");
  assert.equal(r.forecast[r.last], r.history[r.last]);
  assert.equal(r.hi[r.last], r.history[r.last]);
  assert.equal(r.lo[r.last], r.history[r.last]);
  const err = Math.max(...truth.line.map((v, i) => Math.abs(r.history[i] - v)));
  near(err, 0, 0.05, "history vs true line");
  assert.ok(r.historyN.slice(0, n).every((v) => v === truth.n_week), "per-period n");
  const short = items.short;
  assert.equal(short.ok, false);
  assert.ok([...short.forecast, ...short.hi, ...short.lo].every((v) => v === null), "no fan for insufficient data");
  say(`rising: point ${r.forecast[n].toFixed(4)} (truth ${truth.rising_next}), fan [${r.lo[n].toFixed(4)}, ${r.hi[n].toFixed(4)}], max |history - truth| = ${err.toFixed(4)}, n per period = ${truth.n_week}`);
  say(`short: ok=${short.ok}, observed=${short.observed}, fan all null`);
});

