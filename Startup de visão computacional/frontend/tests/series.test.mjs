test("7 gaussian: mean, std, sigma bands and histogram match the generator", { skip }, () => {
  const { payload, truth } = F.gaussian;
  const items = Object.fromEntries(payload.sectors.map((x) => [x.sector, gaussianSeries(x)]));
  for (const name of ["A", "B"]) {
    const s = items[name];
    const t = truth[name];
    near(s.mean, t.mu, 0.01, `${name} mean`);
    near(Math.abs(s.std - t.sd_eff) / t.sd_eff, 0, 0.15, `${name} std (relative)`);
    near(s.sigma1[0], s.mean - s.std, 1e-12, "sigma1 low");
    near(s.sigma2[1], s.mean + 2 * s.std, 1e-12, "sigma2 high");
    near(s.bins.reduce((a, b) => a + b.y * b.width, 0), 1, 1e-9, `${name} histogram area`);
    assert.equal(s.bins.reduce((a, b) => a + b.count, 0), s.n);
    assert.equal(s.qq.length, s.n);
    say(`${name}: mean ${s.mean.toFixed(4)} (truth ${t.mu}), std ${s.std.toFixed(4)} (expected ${t.sd_eff.toFixed(4)}), histogram area 1, bins count ${s.n} periods, flagged=${s.flagged}`);
  }
  assert.equal(items.C.flagged, true);
  assert.ok(items.C.range[0] < 0, "skewed sector curve extends below 0%");
  say(`C: flagged=${items.C.flagged} reasons=${JSON.stringify(items.C.reasons)}, curve starts at ${(items.C.range[0] * 100).toFixed(1)}% (impossible zone drawn)`);
});

